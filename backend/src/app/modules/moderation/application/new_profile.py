"""Работы нового профиля решает модератор профиля (B5, Q34 — «да», 2026-10-14).

У профиля, который ещё ни разу не публиковался, работы портфолио не открывают своих кейсов —
ни по подписи (адаптер `portfolio`), ни по фото без ключа AI (`check_image`): повод с фото
дописывается в кейс профиля, пока тот на проверке, а у черновика кейса нет вовсе — работы
войдут в проверку профиля, когда его отправят. «Одобрить профиль» публикует их
(targets/profile.py). Одна карточка на нового исполнителя вместо карточки на каждую работу и
каждое фото.
"""

from typing import Final

from app.modules.specialists.api import WorkForReview

DRAFT: Final = "draft"
"""Профиль — черновик: работы проверят вместе с ним, когда его отправят."""
PENDING_REVIEW: Final = "pending_review"
"""Профиль на первой проверке: работы ждут в его кейсе."""


def with_profile(work: WorkForReview) -> bool:
    """Работа ждёт проверки вместе с новым профилем: у профиля, который ещё ни разу не
    публиковался, работы решает модератор профиля."""
    return work.pending and work.new_profile
